// ----- Signing / verification -----

export interface WebhookSignature {
  /** Full header value: `t=<unix>,v1=<hex>` */
  header: string;
  /** Hex SHA-256 HMAC. */
  v1: string;
  /** Unix seconds. */
  t: number;
}

/**
 * Sign a raw payload. `atUnixSec` defaults to `Math.floor(Date.now() / 1000)`.
 * The output `header` belongs in the `X-HMD-Signature` HTTP header.
 */
export async function signWebhookPayload(
  rawBody: string,
  secret: string,
  atUnixSec?: number,
): Promise<WebhookSignature> {
  const t = atUnixSec ?? Math.floor(Date.now() / 1000);
  const { createHmac } = await import('node:crypto');
  const v1 = createHmac('sha256', secret).update(`${t}.${rawBody}`, 'utf8').digest('hex');
  return { header: `t=${t},v1=${v1}`, v1, t };
}

export class WebhookVerificationError extends Error {
  readonly code: 'missing_header' | 'malformed_header' | 'stale_timestamp' | 'signature_mismatch';
  constructor(code: WebhookVerificationError['code'], message: string) {
    super(message);
    this.name = 'WebhookVerificationError';
    this.code = code;
  }
}

/**
 * Verify a raw payload against a signature header. Throws WebhookVerificationError on failure.
 * Returns the parsed timestamp on success, callers may also want to `WebhookEventSchema.parse(JSON.parse(rawBody))`.
 */
export async function verifyWebhookPayload(
  rawBody: string,
  header: string | null | undefined,
  secret: string,
  options: { toleranceSec?: number; nowUnixSec?: number } = {},
): Promise<{ t: number }> {
  if (!header || typeof header !== 'string') {
    throw new WebhookVerificationError(
      'missing_header',
      `Missing ${WEBHOOK_SIGNATURE_HEADER} header`,
    );
  }
  const parts = header.split(',').map((p) => p.trim());
  let t: number | undefined;
  let v1: string | undefined;
  for (const part of parts) {
    const eq = part.indexOf('=');
    if (eq <= 0) continue;
    const k = part.slice(0, eq);
    const v = part.slice(eq + 1);
    if (k === 't') t = Number(v);
    else if (k === 'v1') v1 = v;
  }
  if (t === undefined || !Number.isFinite(t) || !v1 || !/^[0-9a-f]{64}$/.test(v1)) {
    throw new WebhookVerificationError('malformed_header', 'Header missing t= or v1= fields');
  }
  const tolerance = options.toleranceSec ?? WEBHOOK_TOLERANCE_SECONDS;
  const now = options.nowUnixSec ?? Math.floor(Date.now() / 1000);
  if (Math.abs(now - t) > tolerance) {
    throw new WebhookVerificationError(
      'stale_timestamp',
      `Timestamp outside ±${tolerance}s tolerance window`,
    );
  }
  const { createHmac } = await import('node:crypto');
  const expected = createHmac('sha256', secret).update(`${t}.${rawBody}`, 'utf8').digest('hex');
  if (!timingSafeHexEqual(expected, v1)) {
    throw new WebhookVerificationError('signature_mismatch', 'HMAC mismatch');
  }
  return { t };
}

function timingSafeHexEqual(a: string, b: string): boolean {
  if (a.length !== b.length) return false;
  let diff = 0;
  for (let i = 0; i < a.length; i++) diff |= a.charCodeAt(i) ^ b.charCodeAt(i);
  return diff === 0;
}
