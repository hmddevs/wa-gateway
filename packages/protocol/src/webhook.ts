/**
 * Webhook contract, HMD WA Gateway → consumer URL.
 *
 * Signing scheme (Stripe-shaped, intentionally familiar):
 *
 *   X-HMD-Signature: t=<unix-seconds>,v1=<hex-sha256>
 *
 * Where `v1 = HMAC-SHA256(secret, `${t}.${rawBody}`)` and `rawBody` is the
 * exact bytes of the JSON request body. Receivers MUST:
 *   1. Parse `t` and `v1` from the header.
 *   2. Reject if `Math.abs(now - t) > WEBHOOK_TOLERANCE_SECONDS`.
 *   3. Recompute the HMAC over `${t}.${rawBody}` and compare in constant time.
 *
 * The signed payload is the raw bytes, DO NOT canonicalise, re-stringify,
 * or normalise before verifying. Frameworks that auto-parse JSON must expose
 * the raw body (e.g., Express `express.raw({ type: 'application/json' })`).
 *
 * Secrets are 32 random bytes encoded base64url. Generated by the gateway,
 * shown to the admin ONCE on route creation, stored hashed-at-rest.
 */
import { z } from 'zod';
import { E164Schema, MessageStatusSchema } from './db.js';

// ----- Header / tolerance constants -----

export const WEBHOOK_SIGNATURE_HEADER = 'X-HMD-Signature' as const;
export const WEBHOOK_EVENT_HEADER = 'X-HMD-Event' as const;
export const WEBHOOK_DELIVERY_HEADER = 'X-HMD-Delivery-Id' as const;
export const WEBHOOK_TOLERANCE_SECONDS = 300; // ±5 min replay window
export const WEBHOOK_HTTP_TIMEOUT_MS = 5_000;

/** Exponential backoff schedule (seconds). After the last entry, mark abandoned. */
export const WEBHOOK_DELIVERY_RETRY_DELAYS_SEC = [30, 120, 600, 3_600, 21_600, 86_400] as const;
export const WEBHOOK_MAX_ATTEMPTS = WEBHOOK_DELIVERY_RETRY_DELAYS_SEC.length + 1;

